"""Builds app/src/main/assets/cities.tsv from GeoNames data.

Source data (GeoNames, https://www.geonames.org, licensed CC BY 4.0):
  https://download.geonames.org/export/dump/cities15000.zip   (unzip to cities15000.txt)
  https://download.geonames.org/export/dump/admin1CodesASCII.txt

Usage (from the project folder):
  python tools/build_cities.py <folder containing cities15000.txt and admin1CodesASCII.txt>

Output columns (tab-separated, UTF-8):
  name, ascii name (empty if same as name), country code, region name,
  latitude, longitude, IANA time zone, population,
  aliases ("|"-separated Latin-script alternative names, only for larger cities,
  so that e.g. "Mecca" finds Makkah and "Medina" finds Madinah)
"""

import os
import re
import sys

# Cities at least this big get alternative-name aliases (keeps the file small).
ALIAS_MIN_POPULATION = 300_000
ALIAS_PATTERN = re.compile(r"^[A-Za-z][A-Za-z '\-]{1,29}$")

OUT = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "assets", "cities.tsv")


def clean(text):
    return text.replace("\t", " ").replace("\n", " ").strip()


def main(src_dir):
    admin1 = {}
    with open(os.path.join(src_dir, "admin1CodesASCII.txt"), encoding="utf-8") as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) >= 2:
                admin1[parts[0]] = clean(parts[1])

    rows = []
    skipped = 0
    with open(os.path.join(src_dir, "cities15000.txt"), encoding="utf-8") as f:
        for line in f:
            p = line.rstrip("\n").split("\t")
            if len(p) < 18:
                skipped += 1
                continue
            name, ascii_name = clean(p[1]), clean(p[2])
            country, region_code, tz = p[8], p[10], p[17].strip()
            try:
                lat, lon = float(p[4]), float(p[5])
                population = int(p[14] or 0)
            except ValueError:
                skipped += 1
                continue
            if not name or not tz or not (-90 <= lat <= 90) or not (-180 <= lon <= 180):
                skipped += 1
                continue
            aliases = []
            if population >= ALIAS_MIN_POPULATION:
                seen = {name.lower(), ascii_name.lower()}
                for alt in p[3].split(","):
                    alt = alt.strip()
                    if ALIAS_PATTERN.match(alt) and alt.lower() not in seen:
                        seen.add(alt.lower())
                        aliases.append(alt)
            rows.append((
                name,
                "" if ascii_name == name else ascii_name,
                country,
                admin1.get(f"{country}.{region_code}", ""),
                f"{lat:.4f}",
                f"{lon:.4f}",
                tz,
                str(population),
                "|".join(aliases),
            ))

    rows.sort(key=lambda r: -int(r[7]))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("# City data from GeoNames (https://www.geonames.org), licensed CC BY 4.0. "
                  "Cities with population over 15,000. Generated by tools/build_cities.py\n")
        for r in rows:
            out.write("\t".join(r) + "\n")
    print(f"wrote {len(rows)} cities, skipped {skipped}, -> {os.path.abspath(OUT)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
