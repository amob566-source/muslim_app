"""Builds the Android launcher icon (adaptive icon layers) from logo/gemini-svg.svg.

Android vector drawables cannot use SVG filters or dashed strokes, so the arch glow is drawn as
a soft wider stroke and the dashed ring as separate arc segments. The logo (512 x 512 units) is
scaled into the 108 dp adaptive-icon canvas so that everything sits inside the 66 dp "safe
zone" that no launcher mask (circle, squircle, teardrop) ever cuts off.

Run:  G:\\Python312\\python.exe -I tools\\build_launcher_icon.py
"""
import math
import pathlib

RES = pathlib.Path(__file__).resolve().parent.parent / "app" / "src" / "main" / "res" / "drawable"

# Logo point (256, 240) -> icon centre (54, 54); 0.16 keeps the arch and crescent within 33 dp.
SCALE = 0.16
TX = 54 - 256 * SCALE
TY = 54 - 240 * SCALE

ARCH = "M136,410 V250 C136,170 256,100 256,100 C256,100 376,170 376,250 V410"
CRESCENT = "M256,62 A16,16 0 1,1 270,82 A13,13 0 1,0 256,62 Z"
NEEDLE_NORTH_LIGHT = "M256,150 L280,245 L256,260 Z"
NEEDLE_NORTH_DARK = "M256,150 L232,245 L256,260 Z"
NEEDLE_SOUTH_LIGHT = "M256,320 L272,260 L256,245 Z"
NEEDLE_SOUTH_DARK = "M256,320 L240,260 L256,245 Z"


def circle(cx, cy, r):
    return f"M{cx - r},{cy} A{r},{r} 0 1,0 {cx + r},{cy} A{r},{r} 0 1,0 {cx - r},{cy} Z"


def dashed_circle(cx, cy, r, dash, gap, per_path=24):
    """Separate dashes replacing SVG stroke-dasharray, split into several short paths (long
    vector paths are slow to draw). Each dash is under 1 dp on screen, so straight is fine."""
    step = dash + gap
    count = int(2 * math.pi * r // step)
    dashes = []
    for i in range(count):
        a0, a1 = (i * step) / r, (i * step + dash) / r
        x0, y0 = cx + r * math.cos(a0), cy + r * math.sin(a0)
        x1, y1 = cx + r * math.cos(a1), cy + r * math.sin(a1)
        dashes.append(f"M{x0:.0f},{y0:.0f}l{x1 - x0:.1f},{y1 - y0:.1f}")
    return ["".join(dashes[i:i + per_path]) for i in range(0, count, per_path)]


def gold_gradient(x0, y0, x1, y1):
    return f"""        <aapt:attr name="android:{{attr}}">
            <gradient
                android:type="linear"
                android:startX="{x0}" android:startY="{y0}"
                android:endX="{x1}" android:endY="{y1}">
                <item android:offset="0" android:color="#FFFCE6A9" />
                <item android:offset="0.5" android:color="#FFE0B865" />
                <item android:offset="1" android:color="#FF9E7326" />
            </gradient>
        </aapt:attr>"""


HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/build_launcher_icon.py from logo/gemini-svg.svg. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
"""

background = HEADER + """    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0" android:startY="0"
                android:endX="108" android:endY="108">
                <item android:offset="0" android:color="#FF08121E" />
                <item android:offset="1" android:color="#FF0E3D3E" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
"""

arch_gradient = gold_gradient(136, 100, 376, 410)
crescent_gradient = gold_gradient(240, 46, 272, 82)

DASHED_RING = "".join(
    f'        <path android:pathData="{d}"\n'
    f'            android:strokeColor="#40E0B865" android:strokeWidth="1.5" />\n'
    for d in dashed_circle(256, 270, 170, 6, 6)
)

foreground = HEADER + f"""    <group android:scaleX="{SCALE}" android:scaleY="{SCALE}" android:translateX="{TX:.2f}" android:translateY="{TY:.2f}">
        <!-- Qibla radar rings -->
{DASHED_RING}        <path android:pathData="{circle(256, 270, 120)}"
            android:strokeColor="#59E0B865" android:strokeWidth="1.5" />
        <!-- Soft glow behind the mihrab arch -->
        <path android:pathData="{ARCH}"
            android:strokeColor="#33E0B865" android:strokeWidth="30"
            android:strokeLineCap="round" android:strokeLineJoin="round" />
        <!-- Mihrab / compass arch (gold) -->
        <path android:pathData="{ARCH}"
            android:strokeWidth="14" android:strokeLineCap="round" android:strokeLineJoin="round">
{arch_gradient.replace("{attr}", "strokeColor")}
        </path>
        <!-- Qibla compass needle -->
        <path android:pathData="{NEEDLE_NORTH_LIGHT}" android:fillColor="#FFFCE6A9" />
        <path android:pathData="{NEEDLE_NORTH_DARK}" android:fillColor="#FFC29438" />
        <path android:pathData="{NEEDLE_SOUTH_LIGHT}" android:fillColor="#FF1C4B4B" />
        <path android:pathData="{NEEDLE_SOUTH_DARK}" android:fillColor="#FF123333" />
        <path android:pathData="{circle(256, 260, 10)}" android:fillColor="#FFFFFFFF" />
        <path android:pathData="{circle(256, 260, 5)}" android:fillColor="#FF08121E" />
        <!-- Crescent at the arch peak -->
        <path android:pathData="{CRESCENT}">
{crescent_gradient.replace("{attr}", "fillColor")}
        </path>
    </group>
</vector>
"""

# Android 13+ "themed icons": one colour, tinted by the system. Arch, needle and crescent only.
monochrome = HEADER + f"""    <group android:scaleX="{SCALE}" android:scaleY="{SCALE}" android:translateX="{TX:.2f}" android:translateY="{TY:.2f}">
        <path android:pathData="{ARCH}"
            android:strokeColor="#FFFFFFFF" android:strokeWidth="16"
            android:strokeLineCap="round" android:strokeLineJoin="round" />
        <path android:pathData="M256,150 L280,245 L256,260 L232,245 Z" android:fillColor="#FFFFFFFF" />
        <path android:pathData="{circle(256, 260, 10)}" android:fillColor="#FFFFFFFF" />
        <path android:pathData="{CRESCENT}" android:fillColor="#FFFFFFFF" />
    </group>
</vector>
"""

for name, text in [("ic_launcher_background.xml", background),
                   ("ic_launcher_foreground.xml", foreground),
                   ("ic_launcher_monochrome.xml", monochrome)]:
    (RES / name).write_text(text, encoding="utf-8", newline="\n")
    print("wrote", RES / name)
